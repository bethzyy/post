def main():
    """主函数：生成所有夏秋冬节气的配图版HTML"""
    output_dir = os.path.dirname(os.path.abspath(__file__))

    # 定义要生成的节气（谷雨+夏秋冬19个）
    terms = ["谷雨", "立夏", "小满", "芒种", "夏至", "小暑", "大暑",
             "立秋", "处暑", "白露", "秋分", "寒露", "霜降",
             "立冬", "小雪", "大雪", "冬至", "小寒", "大寒"]

    generated = 0
    for term in terms:
        if term in SOLAR_TERMS_DATA:
            html_content = generate_html(term, SOLAR_TERMS_DATA[term])
            output_file = os.path.join(output_dir, f"{term}_配图版.html")
            with open(output_file, 'w', encoding='utf-8') as f:
                f.write(html_content)
            print(f"[OK] 生成: {term}_配图版.html")
            generated += 1
        else:
            print(f"[SKIP] 跳过: {term} (无数据)")

    print(f"\n完成! 共生成 {generated} 个配图版HTML文件")

if __name__ == "__main__":
    main()
